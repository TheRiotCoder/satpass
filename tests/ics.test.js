const { ok, near, done, snapshot } = require("./harness");
const I = require("../js/ics.js"), P = require("../js/passes.js"), T = require("../js/tle.js");
const sats = T.parse(snapshot().tle).sats, S = P.makeSat(sats.find(s => s.norad === 25544)), obs = P.makeObserver(30.27, -97.74, 150);
const t0 = Math.ceil(sats.find(s => s.norad === 25544).epochMs / 3600000) * 3600000;
const passes = P.findPasses(S, obs, t0, t0 + 2 * 86400000, { minEl: 10 });
const ics = I.build(passes.slice(0, 3), { observerLabel: "EM10dg, 30.2700°N 97.7400°W", alarmMin: 10, nowMs: Date.UTC(2026, 9, 15, 12), tleAgeDays: 1.2 });
const lines = ics.split("\r\n");
ok("ends with CRLF", ics.endsWith("\r\n") && lines[lines.length - 1] === "");
ok("no bare LF", !/[^\r]\n/.test(ics));
ok("BEGIN/END VCALENDAR", lines[0] === "BEGIN:VCALENDAR" && lines[lines.length - 2] === "END:VCALENDAR");
ok("VERSION & PRODID", lines.includes("VERSION:2.0") && lines.some(l => l.startsWith("PRODID:")));
ok("3 VEVENTs balanced", (ics.match(/BEGIN:VEVENT/g) || []).length === 3 && (ics.match(/END:VEVENT/g) || []).length === 3);
ok("3 VALARMs balanced with TRIGGER", (ics.match(/BEGIN:VALARM/g) || []).length === 3 && (ics.match(/TRIGGER:-PT10M/g) || []).length === 3);
ok("every physical line ≤ 75 octets", lines.every(l => Buffer.byteLength(l, "utf8") <= 75), lines.filter(l => Buffer.byteLength(l) > 75).slice(0, 2));
ok("DTSTART/DTEND are UTC basic format", lines.filter(l => /^DT(START|END):/.test(l)).every(l => /:\d{8}T\d{6}Z$/.test(l)));
const unfolded = ics.replace(/\r\n /g, "");
const ev = unfolded.split("BEGIN:VEVENT")[1];
const get = k => (ev.match(new RegExp("\\r\\n" + k + ":([^\\r]*)")) || [])[1];
ok("DTSTART matches AOS", get("DTSTART") === I.utcStamp(passes[0].aos) && get("DTEND") === I.utcStamp(passes[0].los));
ok("DTSTAMP from nowMs", get("DTSTAMP") === "20261015T120000Z");
ok("UID present and unique", new Set(unfolded.match(/UID:[^\r]+/g)).size === 3);
ok("SUMMARY has sat name and max elevation", /^ISS \(ZARYA\) pass – max \d+°$/.test(get("SUMMARY").replace(/\\/g, "")), get("SUMMARY"));
ok("DESCRIPTION escapes newlines as \\n and carries disclaimer", get("DESCRIPTION").includes("\\n") && get("DESCRIPTION").includes("estimates"));
ok("DTEND after DTSTART", get("DTEND") > get("DTSTART"));
ok("escapeText handles ; , \\ and newline", I.escapeText("a;b,c\\d\ne") === "a\\;b\\,c\\\\d\\ne");
ok("fold keeps multi-byte chars intact", I.fold("X".repeat(70) + "°°°°°°").split("\r\n").every(l => Buffer.byteLength(l) <= 75));
ok("utcStamp", I.utcStamp(Date.UTC(2026, 0, 2, 3, 4, 5)) === "20260102T030405Z");
const noAlarm = I.build(passes.slice(0, 1), { nowMs: 0 });
ok("no VALARM when alarmMin = 0", !/VALARM/.test(noAlarm));
const trunc = I.build([Object.assign({}, passes[0], { truncated: true })], { nowMs: 0 }).replace(/\r\n /g, "");
ok("truncated pass: description says duration is a lower bound", /Duration at least/.test(trunc) && /LOS not found/.test(trunc));
done();
