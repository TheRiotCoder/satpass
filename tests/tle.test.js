const { ok, near, throws, done, snapshot } = require("./harness");
const T = require("../js/tle.js");
const ISS = "ISS (ZARYA)\n1 25544U 98067A   26288.49932320  .00005222  00000+0  10330-3 0  9998\n2 25544  51.6327  64.7113 0006646 265.3101  94.7128 15.48874993590405\n";
let r = T.parse(ISS);
ok("parse 3-line", r.sats.length === 1 && r.sats[0].norad === 25544 && r.sats[0].name === "ISS (ZARYA)" && r.errors.length === 0, r.errors);
near("epoch: 2026 day 288.499323 = Oct 15 11:59:00 UTC", r.sats[0].epochMs, Date.UTC(2026, 9, 15, 11, 59, 0), 2000);
r = T.parse(ISS.split("\n").slice(1).join("\n"));
ok("parse 2-line (no name)", r.sats.length === 1 && r.sats[0].name === "NORAD 25544");
r = T.parse("0 ISS (ZARYA)\n" + ISS.split("\n").slice(1).join("\n"));
ok("parse '0 NAME' 3LE", r.sats[0].name === "ISS (ZARYA)");
const bad = ISS.replace("0006646", "0006647");
r = T.parse(bad);
ok("checksum error rejected", r.sats.length === 0 && /Checksum/.test(r.errors[0]), r.errors);
r = T.parse("garbage\nmore garbage\n");
ok("garbage -> errors, no sats", r.sats.length === 0 && r.errors.length > 0);
r = T.parse(ISS.replace(/\n/g, "\r\n"));
ok("CRLF line endings", r.sats.length === 1);
near("epoch year pivot 98 -> 1998", T.epochMs("1 25544U 98067A   98100.50000000  .00005222  00000+0  10330-3 0  9998"), Date.UTC(1998, 3, 10, 12), 1000);
const a = T.parse(ISS).sats[0], b = Object.assign({}, a, { epochMs: a.epochMs + 1000, name: "NEWER" });
ok("merge keeps newest epoch", T.merge([a], [b])[0].name === "NEWER" && T.merge([b], [a])[0].name === "NEWER" && T.merge([a], [b]).length === 1);
ok("age & stale", Math.abs(T.ageDays(a, a.epochMs + 3 * 86400000) - 3) < 1e-9 && !T.isStale(a, a.epochMs + 6.9 * 86400000) && T.isStale(a, a.epochMs + 7.1 * 86400000));
ok("serialize round trip", T.parse(T.serialize([a])).sats[0].l2 === a.l2);
const snap = snapshot(), p = T.parse(snap.tle);
ok("bundled snapshot: all TLE checksums valid", p.errors.length === 0 && p.sats.length > 150, p.errors.slice(0, 2));
ok("snapshot has fetchedAt timestamp", /^\d{4}-\d\d-\d\dT/.test(snap.fetchedAt), snap.fetchedAt);
const R = require("../js/radio.js");
const missing = R.CURATED.filter(c => !p.sats.some(s => s.norad === c.norad)).map(c => c.short);
ok("curated satellites present in snapshot (allowed missing: only re-entered ones – AO-92, CAS-4A/B – which radio.js marks via status())", missing.every(m => ["AO-92", "CAS-4A", "CAS-4B"].includes(m) && R.status(R.CURATED.find(c => c.short === m).norad).state === "re-entered") && missing.length === 3, missing);
ok("ISS present", p.sats.some(s => s.norad === 25544));
ok("radio table entries reference curated sats", Object.keys(R.RADIO).every(k => R.curated(+k)), Object.keys(R.RADIO).filter(k => !R.curated(+k)));
ok("radio frequencies sane (VHF/UHF/HF)", Object.values(R.RADIO).flat().every(e => [e.up, e.down, e.upLo, e.downLo].filter(Boolean).every(f => f > 20e6 && f < 500e6)));
done();
